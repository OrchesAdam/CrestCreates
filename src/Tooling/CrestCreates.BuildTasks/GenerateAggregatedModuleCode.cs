using Microsoft.Build.Framework;
using Microsoft.Build.Utilities;
using System.Text;

namespace CrestCreates.BuildTasks;

public class GenerateAggregatedModuleCode : Microsoft.Build.Utilities.Task
{
    [Required]
    public string ModuleManifestFile { get; set; } = string.Empty;

    [Required]
    public string OutputPath { get; set; } = string.Empty;

    [Required]
    public string Namespace { get; set; } = string.Empty;

    public override bool Execute()
    {
        try
        {
            if (!File.Exists(ModuleManifestFile))
            {
                Log.LogError($"Module manifest file not found: {ModuleManifestFile}");
                return false;
            }
            var modules = TopologicalSort(CollectModuleManifests.ReadManifest(ModuleManifestFile));
            BuildOutput.WriteIfChanged(OutputPath, GenerateCode(modules));
            Log.LogMessage(MessageImportance.High, $"Generated aggregated module code at {OutputPath} with {modules.Count} modules");
            return true;
        }
        catch (Exception ex)
        {
            Log.LogErrorFromException(ex);
            return false;
        }
    }

    private static List<CollectModuleManifests.ModuleManifest> TopologicalSort(List<CollectModuleManifests.ModuleManifest> modules)
    {
        var identities = new Dictionary<string, CollectModuleManifests.ModuleManifest>(StringComparer.Ordinal);
        foreach (var module in modules)
            if (!identities.TryAdd(module.FullName, module)) throw new InvalidDataException($"Duplicate module identity: {module.FullName}");
        var dependencies = new Dictionary<string, List<CollectModuleManifests.ModuleManifest>>(StringComparer.Ordinal);
        foreach (var module in modules)
        {
            var resolved = new List<CollectModuleManifests.ModuleManifest>();
            foreach (var name in module.DependsOn)
            {
                if (identities.TryGetValue(name, out var exact)) resolved.Add(exact);
                else
                {
                    var matches = modules.Where(candidate => candidate.Name == name).ToList();
                    if (matches.Count != 1) throw new InvalidDataException($"Unknown or ambiguous dependency '{name}' for {module.FullName}");
                    resolved.Add(matches[0]);
                }
            }
            dependencies.Add(module.FullName, resolved);
        }
        var sorted = new List<CollectModuleManifests.ModuleManifest>();
        var remaining = modules.ToDictionary(module => module.FullName, StringComparer.Ordinal);
        var completed = new HashSet<string>(StringComparer.Ordinal);
        while (remaining.Count != 0)
        {
            var next = remaining.Values.Where(module => dependencies[module.FullName].All(dependency => completed.Contains(dependency.FullName)))
                .OrderBy(module => module.Order).ThenBy(module => module.FullName, StringComparer.Ordinal).FirstOrDefault();
            if (next == null) throw new InvalidDataException($"Circular module dependency: {string.Join(", ", remaining.Keys.Order(StringComparer.Ordinal))}");
            sorted.Add(next);
            completed.Add(next.FullName);
            remaining.Remove(next.FullName);
        }
        return sorted;
    }

    private string GenerateCode(List<CollectModuleManifests.ModuleManifest> modules)
    {
        if (modules.Count == 0)
            return $$"""
                // <auto-generated/>
                namespace {{Namespace}};
                internal static partial class ModuleAutoInitializer
                {
                    public static TBuilder RegisterModules<TBuilder>(this TBuilder builder) => builder;
                    public static TCollection RegisterAllModules<TCollection>(this TCollection services) => services;
                    public static System.Threading.Tasks.Task<TProvider> InitializeAllModulesAsync<TProvider>(TProvider serviceProvider)
                        => System.Threading.Tasks.Task.FromResult(serviceProvider);
                    public static System.Threading.Tasks.Task<THost> InitializeModulesAsync<THost>(this THost host)
                        => System.Threading.Tasks.Task.FromResult(host);
                }
                """ + Environment.NewLine;

        var code = new StringBuilder();
        code.AppendLine($$"""
            // <auto-generated/>
            #nullable enable
            namespace {{Namespace}};
            using System;
            using System.Collections.Generic;
            using System.Threading.Tasks;
            using Microsoft.Extensions.DependencyInjection;
            using Microsoft.Extensions.DependencyInjection.Extensions;
            using Microsoft.Extensions.Hosting;
            using Microsoft.Extensions.Logging;
            using CrestCreates.Modularity;
            using CrestCreates.ModuleDiagnostics.Stores;
            using CrestCreates.ModuleDiagnostics.Timing;
            using CrestCreates.ModuleDiagnostics.Modules;
            internal static partial class ModuleAutoInitializer
            {
                public static IReadOnlyList<ModuleDescriptor> RegisteredModules { get; } = Array.AsReadOnly(new ModuleDescriptor[]
                {
            """);
        foreach (var module in modules)
            code.AppendLine($"        new ModuleDescriptor(typeof(global::{module.FullName}), {module.Order}, {module.AutoRegisterServices.ToString().ToLowerInvariant()}),");
        code.AppendLine("    });");
        code.AppendLine("    public static IHostBuilder RegisterModules(this IHostBuilder builder) => builder.ConfigureServices((context, services) => RegisterAllModules(services));");
        code.AppendLine("    public static IServiceCollection RegisterAllModules(IServiceCollection services)");
        code.AppendLine("    {");
        code.AppendLine("        services.AddModuleDiagnostics();");
        foreach (var module in modules) code.AppendLine($"        services.TryAddSingleton<global::{module.FullName}>();");
        foreach (var module in modules.Where(module => module.AutoRegisterServices))
            code.AppendLine($"        services.ConfigureModuleServices<global::{module.FullName}>(static services => new global::{module.FullName}().OnConfigureServices(services));");
        code.AppendLine("        return services;");
        code.AppendLine("    }");
        code.AppendLine("    public static async Task InitializeAllModulesAsync(IServiceProvider serviceProvider)");
        code.AppendLine("    {");
        code.AppendLine("        var initialization = serviceProvider.GetRequiredService<ModuleInitializationState>();");
        code.AppendLine("        var diagnostics = serviceProvider.GetRequiredService<IModuleDiagnosticsStore>();");
        foreach (var module in modules) AppendPhase(code, module, "PreInit", "RunPreInitializationAsync", "OnPreInitializeAsync()", "serviceProvider");
        foreach (var module in modules) AppendPhase(code, module, "Init", "RunInitializationAsync", "OnInitializeAsync()", "serviceProvider");
        foreach (var module in modules) AppendPhase(code, module, "PostInit", "RunPostInitializationAsync", "OnPostInitializeAsync()", "serviceProvider");
        code.AppendLine("    }");
        code.AppendLine("    public static async Task<IHost> InitializeModulesAsync(this IHost host)");
        code.AppendLine("    {");
        code.AppendLine("        await InitializeAllModulesAsync(host.Services);");
        code.AppendLine("        var initialization = host.Services.GetRequiredService<ModuleInitializationState>();");
        code.AppendLine("        var diagnostics = host.Services.GetRequiredService<IModuleDiagnosticsStore>();");
        foreach (var module in modules) AppendPhase(code, module, "AppInit", "RunApplicationInitializationAsync", "OnApplicationInitializationAsync(host)", "host.Services");
        code.AppendLine("        var logger = host.Services.GetService<ILogger<IModule>>();");
        code.AppendLine("        if (logger != null) foreach (var diagnostic in diagnostics.GetAll())");
        code.AppendLine("            logger.Log(diagnostic.Status == ModulePhaseStatus.Failed ? LogLevel.Error : LogLevel.Information, \"[ModuleDiagnostics] {Module} {Phase}: {Status} ({Elapsed}ms) {Error}\", diagnostic.ModuleName, diagnostic.Phase, diagnostic.Status, diagnostic.Elapsed.TotalMilliseconds, diagnostic.ErrorMessage);");
        code.AppendLine("        return host;");
        code.AppendLine("    }");
        code.AppendLine("}");
        return code.ToString();
    }

    private static void AppendPhase(StringBuilder code, CollectModuleManifests.ModuleManifest module, string phase, string gate, string hook, string provider)
    {
        code.AppendLine($"        await initialization.{gate}(typeof(global::{module.FullName}), async () =>");
        code.AppendLine("        {");
        code.AppendLine($"            var timer = ModulePhaseTimer.StartNew(typeof(global::{module.FullName}).FullName!, \"{phase}\");");
        code.AppendLine("            try");
        code.AppendLine("            {");
        code.AppendLine($"                await {provider}.GetRequiredService<global::{module.FullName}>().{hook};");
        code.AppendLine("                diagnostics.Record(timer.Stop(ModulePhaseStatus.Success));");
        code.AppendLine("            }");
        code.AppendLine("            catch (Exception error)");
        code.AppendLine("            {");
        code.AppendLine("                diagnostics.Record(timer.StopFailed(error));");
        code.AppendLine("                throw;");
        code.AppendLine("            }");
        code.AppendLine("        });");
    }

    public class ModuleManifest : CollectModuleManifests.ModuleManifest;
}
