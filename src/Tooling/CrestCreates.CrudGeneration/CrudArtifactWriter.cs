#nullable enable
using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace CrestCreates.Tooling.CrudGeneration;

/// <summary>
/// Shared text primitives for every CRUD artifact family: stable indentation, document headers,
/// namespace blocks and artifact identity. Keeping them in one place guarantees every artifact and the
/// bundle observe the same bytes.
/// </summary>
internal static class CrudArtifactWriter
{
    /// <summary>Separator written between artifacts inside one bundle, so every block stays attributable.</summary>
    internal const string ArtifactSeparator = "// ---- artifact: ";

    internal const string Indent = "    ";

    internal const string NestedIndent = Indent + Indent;

    internal const string TripleIndent = NestedIndent + Indent;

    internal const string QuadIndent = TripleIndent + Indent;

    internal static string Qualified(string fullName) => "global::" + fullName;

    internal static IReadOnlyList<CrudGenerationModel> CanonicalOrder(
        IReadOnlyList<CrudGenerationModel> models) =>
        models.Count > 1
            ? models.OrderBy(model => model.ServiceFullName, StringComparer.Ordinal).ToArray()
            : models;

    internal static string Escape(string value) =>
        value.Replace("\\", "\\\\").Replace("\"", "\\\"");

    internal static StringBuilder StartDocument(CrudGenerationModel model)
    {
        var builder = new StringBuilder();
        Line(builder, "// <auto-generated />");
        Line(builder, "// CrestCreates CRUD generated surface. Owner: " + model.OwnerAssemblyName
            + "|" + model.ServiceFullName + ". Model: " + CrudGenerationModel.ModelSchemaVersion + ". Do not edit.");
        Line(builder, "#nullable enable");
        Line(builder, string.Empty);
        return builder;
    }

    internal static void OpenNamespace(StringBuilder builder, string namespaceName, IEnumerable<string>? usings = null)
    {
        Line(builder, "namespace " + namespaceName);
        Line(builder, "{");
        if (usings is not null)
        {
            foreach (var usingStatement in usings)
            {
                Line(builder, Indent + usingStatement);
            }

            Line(builder, string.Empty);
        }
    }

    internal static void CloseNamespace(StringBuilder builder) => Line(builder, "}");

    internal static void Line(StringBuilder builder, string text)
    {
        builder.Append(text);
        builder.Append('\n');
    }

    internal static CrudArtifact Artifact(string hintName, StringBuilder builder)
    {
        var source = builder.ToString();
        return new CrudArtifact(hintName, hintName, source);
    }
}
