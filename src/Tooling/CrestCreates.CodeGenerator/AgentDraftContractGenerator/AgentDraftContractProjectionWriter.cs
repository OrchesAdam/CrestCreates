    /// <summary>
    /// Escapes a property name for use as a C# local variable.
    /// Currently a no-op, but reserved for future collision avoidance.
    /// </summary>
    private static string EscapeVarName(string propertyName)
    {
        // Sanitize: replace any characters unsafe for C# identifiers (should not be needed for property names)
        return propertyName.Replace(".", "_").Replace("<", "_").Replace(">", "_");
    }

    private static bool IsCollectionType(ITypeSymbol type)
    {
        if (type.SpecialType == SpecialType.System_String)
            return false;

        if (type is IArrayTypeSymbol)
            return true;

        if (type is INamedTypeSymbol namedType)
        {
            foreach (var iface in namedType.AllInterfaces)
            {
                if (iface.OriginalDefinition.SpecialType ==
                    SpecialType.System_Collections_Generic_IEnumerable_T)
                    return true;
            }
        }

        return false;
    }

    private static string GetElementTypeFqn(ITypeSymbol type)
    {
        if (type is IArrayTypeSymbol arrayType)
            return arrayType.ElementType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

        if (type is INamedTypeSymbol namedType)
        {
            // Look for IEnumerable<T> to get the element type
            foreach (var iface in namedType.AllInterfaces)
            {
                if (iface.OriginalDefinition.SpecialType ==
                    SpecialType.System_Collections_Generic_IEnumerable_T
                    && iface.TypeArguments.Length == 1)
                {
                    return iface.TypeArguments[0].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                }
            }

            // If the type itself is generic with one type arg, use that
            if (namedType.TypeArguments.Length == 1)
                return namedType.TypeArguments[0].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        }

        return "object";
    }
