using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace CrestCreates.CodeGenerator.EventDescriptorGenerator;

internal static class EventDescriptorCodeWriter
{
    public static string Write(
        string assemblyName,
        IReadOnlyList<EventDescriptorSourceGenerator.EventDeclaration> declarations,
        bool emitCodecContribution)
    {
        var identifier = SanitizeIdentifier(assemblyName);

        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        builder.AppendLine("namespace CrestCreates.Generated");
        builder.AppendLine("{");
        builder.AppendLine($"    internal sealed class {identifier}_EventDescriptorProvider : global::CrestCreates.Event.Abstractions.IEventDescriptorProvider");
        builder.AppendLine("    {");
        builder.AppendLine("        public global::System.Collections.Generic.IReadOnlyList<global::CrestCreates.Event.Abstractions.GeneratedEventDescriptor> GetDescriptors()");
        builder.AppendLine("            => new global::CrestCreates.Event.Abstractions.GeneratedEventDescriptor[]");
        builder.AppendLine("        {");

        foreach (var declaration in declarations)
        {
            builder.AppendLine("            new global::CrestCreates.Event.Abstractions.GeneratedEventDescriptor");
            builder.AppendLine("            {");
            if (declaration.ExplicitId is not null)
            {
                builder.AppendLine($"                Id = \"{EscapeString(declaration.ExplicitId)}\",");
            }
            else
            {
                builder.AppendLine($"                Id = global::CrestCreates.Event.Abstractions.GeneratedEventDescriptor.GenerateId(\"{EscapeString(declaration.Name)}\"),");
            }

            builder.AppendLine($"                Name = \"{EscapeString(declaration.Name)}\",");
            builder.AppendLine($"                Version = {declaration.Version},");
            builder.AppendLine("                State = global::CrestCreates.Metadata.Abstractions.DescriptorState.Active,");
            builder.AppendLine($"                PayloadType = typeof({declaration.TypeDisplayName}),");
            builder.AppendLine($"                Scope = global::CrestCreates.Event.Abstractions.EventScope.{declaration.Scope},");
            builder.AppendLine($"                Reliability = global::CrestCreates.Event.Abstractions.EventReliability.{declaration.Reliability},");

            if (declaration.Importance is not null)
            {
                builder.AppendLine($"                Importance = global::CrestCreates.Event.Abstractions.EventImportance.{declaration.Importance},");
            }

            if (declaration.RequiresIdempotency)
            {
                builder.AppendLine("                RequiresIdempotency = true,");
            }

            if (declaration.IsAuditable)
            {
                builder.AppendLine("                IsAuditable = true,");
            }

            if (declaration.IsReplayable)
            {
                builder.AppendLine("                IsReplayable = true,");
            }

            if (declaration.IsPublic)
            {
                builder.AppendLine("                IsPublic = true,");
            }

            if (declaration.Description is not null)
            {
                builder.AppendLine($"                Description = \"{EscapeString(declaration.Description)}\",");
            }

            if (declaration.CapabilityId is not null)
            {
                builder.AppendLine($"                CapabilityId = \"{EscapeString(declaration.CapabilityId)}\",");
            }

            builder.AppendLine("            },");
        }

        builder.AppendLine("        };");
        builder.AppendLine("    }");
        builder.AppendLine("}");
        builder.AppendLine();
        builder.AppendLine($"namespace CrestCreates.Generated.{identifier}");
        builder.AppendLine("{");
        builder.AppendLine("    /// <summary>");
        builder.AppendLine("    /// Explicit activation for this assembly's canonical event descriptor contribution.");
        builder.AppendLine("    /// Call this from the host composition — there is no scanning fallback.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine("    public static class EventRegistrations");
        builder.AppendLine("    {");
        builder.AppendLine("        public static global::Microsoft.Extensions.DependencyInjection.IServiceCollection AddEventDescriptors(");
        builder.AppendLine("            this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)");
        builder.AppendLine("        {");
        builder.AppendLine("            global::Microsoft.Extensions.DependencyInjection.Extensions.ServiceCollectionDescriptorExtensions.TryAddEnumerable(");
        builder.AppendLine("                services,");
        builder.AppendLine("                new global::Microsoft.Extensions.DependencyInjection.ServiceDescriptor[]");
        builder.AppendLine("                {");
        builder.AppendLine("                    new global::Microsoft.Extensions.DependencyInjection.ServiceDescriptor(");
        builder.AppendLine("                        typeof(global::CrestCreates.Event.Abstractions.IEventDescriptorProvider),");
        builder.AppendLine($"                        typeof(global::CrestCreates.Generated.{identifier}_EventDescriptorProvider),");
        builder.AppendLine("                        global::Microsoft.Extensions.DependencyInjection.ServiceLifetime.Singleton),");
        builder.AppendLine("                });");
        builder.AppendLine();

        if (emitCodecContribution)
        {
            builder.AppendLine("            global::CrestCreates.Generated.EventJsonCodecContributions.Register();");
            builder.AppendLine();
        }

        builder.AppendLine("            return services;");
        builder.AppendLine("        }");
        builder.AppendLine("    }");
        builder.AppendLine("}");

        return builder.ToString();
    }

    private static string SanitizeIdentifier(string value)
    {
        var builder = new StringBuilder(value.Length);
        foreach (var ch in value)
        {
            builder.Append(char.IsLetterOrDigit(ch) || ch == '_' ? ch : '_');
        }

        return builder.Length == 0 ? "Assembly" : builder.ToString();
    }

    private static string EscapeString(string value)
        => value.Replace("\\", "\\\\").Replace("\"", "\\\"");
}
