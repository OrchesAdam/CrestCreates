using System.Text;

namespace CrestCreates.CodeGenerator.AppServiceCompatibilityGenerator;

/// <summary>
/// Emits a projection manifest listing every projected action
/// with its complete mapping from legacy CrestService method to
/// CapabilityDescriptor + CapabilityEndpointDescriptor.
/// Implements IAppServiceCompatibilityProjectionManifestProvider.
/// </summary>
internal static class AppServiceCompatibilityManifestEmitter
{
    public static string Emit(CompatibilityServiceModel service)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using System.Runtime.CompilerServices;");
        sb.AppendLine("using CrestCreates.DynamicApi.Abstractions;");
        sb.AppendLine("using CrestCreates.Metadata.Abstractions.DescriptorCapability;");
        sb.AppendLine();
        sb.AppendLine("namespace CrestCreates.Generated;");
        sb.AppendLine();
        sb.AppendLine($"internal sealed class GeneratedAppServiceCompatibilityManifest_{service.SanitizedIdentifier} : IAppServiceCompatibilityProjectionManifestProvider");
        sb.AppendLine("{");
        sb.AppendLine("    public IReadOnlyList<AppServiceCompatibilityProjectionEntry> GetEntries() => Entries;");
        sb.AppendLine();
        sb.AppendLine("    public static readonly IReadOnlyList<AppServiceCompatibilityProjectionEntry> Entries = new AppServiceCompatibilityProjectionEntry[]");
        sb.AppendLine("    {");

        foreach (var action in service.Actions)
        {
            var invokerClassName = $"{service.ServiceName}_{action.ActionName}_CompatibilityInvoker";
            var permissionExpr = string.IsNullOrEmpty(action.PermissionName)
                ? "System.Array.Empty<string>()"
                : $"new[] {{ \"{Escape(action.PermissionName)}\" }}";

            sb.AppendLine("        new AppServiceCompatibilityProjectionEntry");
            sb.AppendLine("        {");
            sb.AppendLine($"            SourceService = \"{Escape(service.ServiceName)}\",");
            sb.AppendLine($"            SourceMethod = \"{Escape(action.ServiceMethodName)}\",");
            sb.AppendLine($"            CapabilityId = \"{Escape(action.CapabilityId)}\",");
            sb.AppendLine($"            EndpointId = \"{Escape(action.EndpointId)}\",");
            sb.AppendLine($"            HttpMethod = \"{Escape(action.HttpMethod)}\",");
            sb.AppendLine($"            RoutePattern = \"{Escape(action.RoutePattern)}\",");
            sb.AppendLine($"            PermissionNames = {permissionExpr},");
            sb.AppendLine($"            InvokerTypeName = \"{Escape(invokerClassName)}\",");
            sb.AppendLine("            ProjectionKind = CapabilityProjectionKind.AppServiceCompatibility,");
            sb.AppendLine("        },");
        }

        sb.AppendLine("    };");
        sb.AppendLine("}");
        sb.AppendLine();

        // ModuleInitializer for registration
        sb.AppendLine($"internal static class GeneratedAppServiceCompatibilityManifest_{service.SanitizedIdentifier}_Initializer");
        sb.AppendLine("{");
        sb.AppendLine("    [ModuleInitializer]");
        sb.AppendLine("    internal static void Initialize()");
        sb.AppendLine("    {");
        sb.AppendLine($"        AppServiceCompatibilityProjectionManifestRegistry.Register(new GeneratedAppServiceCompatibilityManifest_{service.SanitizedIdentifier}());");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        return sb.ToString();
    }

    private static string Escape(string value) => value.Replace("\\", "\\\\").Replace("\"", "\\\"");
}
