using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace CrestCreates.CodeGenerator.LocalEventGenerator;

internal static class LocalEventCodeWriter
{
    public static string Write(
        string assemblyName,
        IReadOnlyList<string> eventNames,
        IReadOnlyDictionary<string, List<HandlerBindingInfo>> handlersByEvent,
        IReadOnlyDictionary<string, EventDeclarationInfo> declarations,
        bool emitCodecContribution)
    {
        var escapedAssembly = EscapeString(assemblyName);
        var contributorId = SanitizeIdentifier(assemblyName);
        var extensionNamespace = SanitizeNamespace(assemblyName);

        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        builder.AppendLine("namespace CrestCreates.Generated");
        builder.AppendLine("{");
        builder.AppendLine($"    internal sealed class {contributorId}_LocalEventContributor : global::CrestCreates.EventBus.Abstractions.ILocalEventRegistrationContributor");
        builder.AppendLine("    {");
        builder.AppendLine($"        internal static readonly {contributorId}_LocalEventContributor Instance = new();");
        builder.AppendLine();
        builder.AppendLine($"        public string ContributorId => \"{escapedAssembly}\";");
        builder.AppendLine();
        builder.AppendLine("        public void Register(global::CrestCreates.EventBus.Abstractions.LocalEventDispatchRegistrationBuilder builder)");
        builder.AppendLine("        {");

        for (var index = 0; index < eventNames.Count; index++)
        {
            var eventName = eventNames[index];
            var handlers = OrderedHandlers(handlersByEvent, eventName);
            var declaration = declarations.TryGetValue(eventName, out var declared) ? declared : null;
            var fieldName = $"_expectedHandlers{index}";

            var eventGlobalName = handlers.Count > 0
                ? handlers[0].EventGlobalName
                : $"global::{eventName}";

            var version = declaration?.Version ?? 1;
            var replayable = declaration?.Replayable ?? false;
            var codecArgument = replayable
                ? $"static () => global::CrestCreates.EventBus.Abstractions.LocalEventJsonCodecRegistry.Resolve(typeof({eventGlobalName}))"
                : "null";
            var legacyArgument = BuildLegacyIdentities(declaration);
            var replayableText = replayable ? "true" : "false";

            builder.AppendLine();
            builder.AppendLine($"            builder.Add(global::CrestCreates.EventBus.Abstractions.LocalEventBinding.Create<{eventGlobalName}>(");
            builder.AppendLine($"                new global::CrestCreates.EventBus.Abstractions.LocalEventInvoker<{eventGlobalName}>(static (provider, @event, cancellationToken) =>");
            builder.AppendLine($"                    global::CrestCreates.EventBus.Abstractions.LocalEventDispatch.InvokeHandlersAsync(provider, @event, cancellationToken)),");
            builder.AppendLine($"                {version},");
            builder.AppendLine($"                {replayableText},");
            builder.AppendLine($"                {codecArgument},");
            builder.AppendLine($"                {fieldName},");
            builder.AppendLine($"                {legacyArgument},");
            builder.AppendLine($"                \"{escapedAssembly}\"));");
        }

        builder.AppendLine("        }");
        builder.AppendLine();

        for (var index = 0; index < eventNames.Count; index++)
        {
            var handlers = OrderedHandlers(handlersByEvent, eventNames[index]);
            var fieldName = $"_expectedHandlers{index}";
            var handlerList = string.Join(", ", handlers.Select(handler => $"typeof({handler.HandlerGlobalName})"));
            builder.AppendLine($"        private static readonly global::System.Type[] {fieldName} = new global::System.Type[] {{ {handlerList} }};");
        }

        builder.AppendLine("    }");
        builder.AppendLine("}");
        builder.AppendLine();

        AppendExtension(builder, extensionNamespace, contributorId, eventNames, handlersByEvent, emitCodecContribution);
        return builder.ToString();
    }

    private static List<HandlerBindingInfo> OrderedHandlers(
        IReadOnlyDictionary<string, List<HandlerBindingInfo>> handlersByEvent,
        string eventName)
        => handlersByEvent.TryGetValue(eventName, out var handlers)
            ? handlers.OrderBy(handler => handler.HandlerMetadataName, StringComparer.Ordinal).ToList()
            : new List<HandlerBindingInfo>();

    private static string BuildLegacyIdentities(EventDeclarationInfo? declaration)
    {
        if (declaration is null || declaration.LegacyIdentities.IsDefaultOrEmpty)
        {
            return "null";
        }

        var entries = string.Join(", ",
            declaration.LegacyIdentities
                .OrderBy(identity => identity.Name, StringComparer.Ordinal)
                .ThenBy(identity => identity.Version)
                .Select(identity =>
                    $"new global::CrestCreates.EventBus.Abstractions.LocalEventLegacyIdentity(\"{EscapeString(identity.Name)}\", {identity.Version})"));

        return $"new global::CrestCreates.EventBus.Abstractions.LocalEventLegacyIdentity[] {{ {entries} }}";
    }

    private static void AppendExtension(
        StringBuilder builder,
        string extensionNamespace,
        string contributorId,
        IReadOnlyList<string> eventNames,
        IReadOnlyDictionary<string, List<HandlerBindingInfo>> handlersByEvent,
        bool emitCodecContribution)
    {
        builder.AppendLine($"namespace {extensionNamespace}");
        builder.AppendLine("{");
        builder.AppendLine("    /// <summary>");
        builder.AppendLine("    /// Explicit activation for this assembly's local event dispatch registrations.");
        builder.AppendLine("    /// Call this from the host composition (or the owning framework package) — there is no scanning fallback.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine("    public static class LocalEventRegistrations");
        builder.AppendLine("    {");
        builder.AppendLine("        public static global::Microsoft.Extensions.DependencyInjection.IServiceCollection AddLocalEvents(");
        builder.AppendLine("            this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)");
        builder.AppendLine("        {");
        builder.AppendLine("            global::Microsoft.Extensions.DependencyInjection.Extensions.ServiceCollectionDescriptorExtensions.TryAddEnumerable(");
        builder.AppendLine("                services,");
        builder.AppendLine("                new global::Microsoft.Extensions.DependencyInjection.ServiceDescriptor[]");
        builder.AppendLine("                {");

        foreach (var eventName in eventNames)
        {
            if (!handlersByEvent.TryGetValue(eventName, out var handlers))
            {
                continue;
            }

            foreach (var handler in handlers.OrderBy(h => h.HandlerMetadataName, StringComparer.Ordinal))
            {
                builder.AppendLine("                    new global::Microsoft.Extensions.DependencyInjection.ServiceDescriptor(");
                builder.AppendLine($"                        typeof(global::CrestCreates.EventBus.Abstractions.ILocalEventHandler<{handler.EventGlobalName}>),");
                builder.AppendLine($"                        typeof({handler.HandlerGlobalName}),");
                builder.AppendLine("                        global::Microsoft.Extensions.DependencyInjection.ServiceLifetime.Scoped),");
            }
        }

        builder.AppendLine("                });");

        builder.AppendLine("            global::Microsoft.Extensions.DependencyInjection.ServiceCollectionServiceExtensions.AddSingleton<global::CrestCreates.EventBus.Abstractions.ILocalEventRegistrationContributor>(");
        builder.AppendLine($"                services, global::CrestCreates.Generated.{contributorId}_LocalEventContributor.Instance);");

        if (emitCodecContribution)
        {
            builder.AppendLine("            global::CrestCreates.Generated.LocalEventJsonCodecContributions.Register();");
        }

        builder.AppendLine("            return services;");
        builder.AppendLine("        }");
        builder.AppendLine("    }");
        builder.AppendLine("}");
    }

    private static string SanitizeIdentifier(string value)
    {
        var builder = new StringBuilder(value.Length);
        foreach (var ch in value)
        {
            builder.Append(char.IsLetterOrDigit(ch) || ch == '_' ? ch : '_');
        }

        return builder.Length == 0 ? "Assembly" : builder.ToString();
    }

    private static string SanitizeNamespace(string assemblyName)
        => "CrestCreates.Generated." + SanitizeIdentifier(assemblyName);

    private static string EscapeString(string value)
        => value.Replace("\\", "\\\\").Replace("\"", "\\\"");
}
