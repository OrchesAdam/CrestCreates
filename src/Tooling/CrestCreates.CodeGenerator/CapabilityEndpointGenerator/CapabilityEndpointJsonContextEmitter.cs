using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace CrestCreates.CodeGenerator.CapabilityEndpointGenerator;

internal static class CapabilityEndpointJsonContextEmitter
{
    /// <summary>
    /// Emits a JsonSerializerContext partial class with [JsonSerializable] for all body types
    /// found in the endpoint group's specs.
    /// </summary>
    public static string EmitJsonContext(ContainerEndpointGroup group)
    {
        var bodyTypes = CollectBodyTypes(group);
        if (bodyTypes.Count == 0)
            return string.Empty; // No body types → no context needed

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System.Text.Json.Serialization;");
        sb.AppendLine();

        if (!string.IsNullOrEmpty(group.ContainerNamespace))
        {
            sb.AppendLine($"namespace {group.ContainerNamespace};");
            sb.AppendLine();
        }

        var safeClassName = SanitizeClassName(group.ContainerClassName);
        sb.AppendLine($"[JsonSerializable(typeof({bodyTypes.First()}))");

        foreach (var type in bodyTypes.Skip(1))
        {
            sb.AppendLine($"   ,JsonSerializable(typeof({type}))");
        }

        sb.AppendLine("   ]");
        sb.AppendLine($"internal sealed partial class GeneratedCapabilityEndpointJsonContext : JsonSerializerContext");
        sb.AppendLine("{");
        sb.AppendLine("}");

        return sb.ToString();
    }

    /// <summary>
    /// Returns the JsonContext class name for use in generated binding code.
    /// </summary>
    public static string GetContextClassName(string containerClassName)
    {
        return $"GeneratedCapabilityEndpointJsonContext";
    }

    /// <summary>
    /// Returns the property accessor for a body type in the generated context.
    /// Pattern: GeneratedCapabilityEndpointJsonContext.Default.{TypeName}
    /// </summary>
    public static string GetTypeInfoAccessor(string containerClassName, string typeName)
    {
        // For types with generics, we need the property name format STJ uses
        // e.g., List<BookDto> → ListBookDto
        var propertyName = ToStjPropertyName(typeName);
        return $"GeneratedCapabilityEndpointJsonContext.Default.{propertyName}";
    }

    private static HashSet<string> CollectBodyTypes(ContainerEndpointGroup group)
    {
        var bodyTypes = new HashSet<string>();
        foreach (var spec in group.Specs)
        {
            foreach (var input in spec.Inputs)
            {
                if (input.SourceValue == 3) // Body
                {
                    bodyTypes.Add(input.TypeName);
                }
            }
        }
        return bodyTypes;
    }

    /// <summary>
    /// Converts a type name to the STJ-generated property name format.
    /// STJ generates property names by removing dots, angle brackets, commas, spaces,
    /// and global:: markers.
    /// e.g., "CreateBookRequest" → "CreateBookRequest"
    /// e.g., "global::TestNs.CreateDto" → "TestNsCreateDto"
    /// e.g., "List&lt;BookDto&gt;" → "ListBookDto"
    /// e.g., "IReadOnlyList&lt;AgentMemoryCompressionPromptSource&gt;" → "IReadOnlyListAgentMemoryCompressionPromptSource"
    /// </summary>
    private static string ToStjPropertyName(string typeName)
    {
        // Strip global:: prefix
        var name = typeName.StartsWith("global::") 
            ? typeName.Substring("global::".Length) 
            : typeName;

        // Also strip any remaining global:: markers (e.g., in nested generic type args)
        name = name.Replace("global::", "");
        
        // Remove dots, generic angle brackets, commas, spaces, and colons
        // STJ keeps the full namespace path, just removes punctuation
        var result = new StringBuilder();
        foreach (var c in name)
        {
            if (c == '<' || c == '>' || c == ',' || c == ' ' || c == '.' || c == ':')
                continue;
            result.Append(c);
        }
        return result.ToString();
    }

    private static string SanitizeClassName(string name) => name.Replace(".", "_");
}
