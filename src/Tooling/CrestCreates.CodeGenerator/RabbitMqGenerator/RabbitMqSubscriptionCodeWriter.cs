        builder.AppendLine($"                    PayloadType = typeof({subscription.PayloadTypeDisplay}),");
        builder.AppendLine($"                    HandlerType = typeof({subscription.HandlerTypeDisplay}),");
        builder.AppendLine($"                    HandlerMethod = \"{EscapeString(subscription.HandlerMethod)}\",");

        if (subscription.Exchange is not null)
        {
            builder.AppendLine($"                    Exchange = \"{EscapeString(subscription.Exchange)}\",");
        }

        if (subscription.Queue is not null)
        {
            builder.AppendLine($"                    Queue = \"{EscapeString(subscription.Queue)}\",");
        }

        if (subscription.RoutingKey is not null)
        {
            builder.AppendLine($"                    RoutingKey = \"{EscapeString(subscription.RoutingKey)}\",");
