    {
        builder.AppendLine("                new global::CrestCreates.EventBus.RabbitMQ.Registration.RabbitMqSubscriptionBinding");
        builder.AppendLine("                {");
        builder.AppendLine($"                    EventName = \"{EscapeString(subscription.EventName)}\",");
