    }

    private static void EmitBinder(StringBuilder builder, HttpWireAction action)
    {
        var hasBody = action.Parameters.Any(parameter => parameter.Source == "Body");
        Line(builder, NestedIndent + "private static "
            + (hasBody ? "async " : string.Empty)
            + "global::System.Threading.Tasks.ValueTask<object?> " + BinderName(action) + "(");
        Line(builder, NestedIndent + Indent + "global::Microsoft.AspNetCore.Http.HttpContext context,");
        Line(builder, NestedIndent + Indent + "global::System.Threading.CancellationToken ct)");
        Line(builder, NestedIndent + "{");
        foreach (var parameter in action.Parameters)
        {
            switch (parameter.Source)
            {
                case "Route":
                    EmitParse(builder, parameter,
                        "context.Request.RouteValues[\"" + Escape(parameter.Name) + "\"]?.ToString()", "route");
                    break;
                case "Query":
                    EmitParse(builder, parameter,
                        "context.Request.Query[\"" + Escape(parameter.Name) + "\"].ToString()", "query");
                    break;
                case "Header":
                    var headerRead = "global::System.Linq.Enumerable.FirstOrDefault(context.Request.Headers[\""
                        + Escape(parameter.HeaderName ?? "If-Match") + "\"])";
                    if (parameter.TrimQuotes)
                    {
                        headerRead += "?.Trim('\"')";
                    }

                    Line(builder, NestedIndent + Indent + "var " + parameter.MemberName + " = " + headerRead + ";");
                    break;
                case "Body":
                    Line(builder, NestedIndent + Indent + "var bodyTypeInfo = " + DynamicApi + "CapabilityEndpointJsonTypeInfoResolver.Require<"
                        + parameter.TypeFullName + ">(context.RequestServices);");
                    Line(builder, NestedIndent + Indent + "var body = await " + DynamicApi + "CapabilityEndpointBodyReader.ReadNativeBodyAsync(");
                    Line(builder, NestedIndent + Indent + Indent + "context, bodyTypeInfo, optional: "
                        + (action.BodyOptional ? "true" : "false") + ", ct);");
                    break;
            }
        }

        if (action.UsesEnvelope && action.EnvelopeFullName is not null)
        {
            Line(builder, NestedIndent + Indent + "var envelope = new global::" + action.EnvelopeFullName);
            Line(builder, NestedIndent + Indent + "{");
            foreach (var parameter in action.Parameters.Where(parameter => parameter.Source != "CancellationToken"))
            {
                Line(builder, NestedIndent + Indent + Indent + parameter.MemberName + " = "
                    + (parameter.Source == "Body" ? "body!" : parameter.LocalName ?? parameter.MemberName) + ",");
            }

            Line(builder, NestedIndent + Indent + "};");
            Line(builder, NestedIndent + Indent + (hasBody
                ? "return envelope;"
                : "return global::System.Threading.Tasks.ValueTask.FromResult<object?>(envelope);"));
        }
        else
        {
            var single = action.Parameters.FirstOrDefault(parameter => parameter.Source != "CancellationToken");
            Line(builder, NestedIndent + Indent + (hasBody
                ? "return body;"
                : single is null
                    ? "return global::System.Threading.Tasks.ValueTask.FromResult<object?>(null);"
                    : "return global::System.Threading.Tasks.ValueTask.FromResult<object?>("
                      + (single.Source == "Body" ? "body!" : single.LocalName ?? single.MemberName) + ");"));
        }

        Line(builder, NestedIndent + "}");
        Line(builder, string.Empty);
    }

    private static void EmitParse(StringBuilder builder, HttpWireParameter parameter, string expression, string source)
    {
        var local = parameter.LocalName ?? parameter.MemberName;
        var failure = "throw new global::Microsoft.AspNetCore.Http.BadHttpRequestException("
            + "\"The " + source + " value '" + Escape(parameter.Name) + "' is missing or not a valid "
            + Escape(MessageType(parameter.TypeFullName)) + ".\");";
        if (parameter.ScalarKind == AppServiceHttpScalarKind.String)
        {
            Line(builder, NestedIndent + Indent + "var " + local + "Text = " + expression + ";");
            if (parameter.Required)
            {
                Line(builder, NestedIndent + Indent + "if (global::System.String.IsNullOrEmpty(" + local + "Text))");
                Line(builder, NestedIndent + Indent + "{");
                Line(builder, NestedIndent + Indent + Indent + failure);
                Line(builder, NestedIndent + Indent + "}");
                Line(builder, NestedIndent + Indent + "var " + local + " = " + local + "Text;");
            }
            else
            {
                Line(builder, NestedIndent + Indent + "var " + local + " = global::System.String.IsNullOrEmpty(" + local + "Text) ? null : " + local + "Text;");
            }

            return;
        }

        if (parameter.ScalarKind == AppServiceHttpScalarKind.Enum)
        {
            var enumType = EnumTypeForParse(parameter.TypeFullName);
            Line(builder, NestedIndent + Indent + "var " + local + "Text = " + expression + ";");
            if (parameter.Required)
            {
                Line(builder, NestedIndent + Indent + "if (global::System.String.IsNullOrEmpty(" + local + "Text) || !global::System.Enum.TryParse(typeof("
                    + enumType + "), " + local + "Text, ignoreCase: true, out var " + local + "Value))");
                Line(builder, NestedIndent + Indent + "{");
                Line(builder, NestedIndent + Indent + Indent + failure);
                Line(builder, NestedIndent + Indent + "}");
                Line(builder, NestedIndent + Indent + "var " + local + " = (" + parameter.TypeFullName + ")" + local + "Value!;");
            }
            else
            {
                Line(builder, NestedIndent + Indent + parameter.TypeFullName + " " + local + " = default!;");
                Line(builder, NestedIndent + Indent + "if (!global::System.String.IsNullOrEmpty(" + local + "Text))");
                Line(builder, NestedIndent + Indent + "{");
                Line(builder, NestedIndent + Indent + Indent + "if (!global::System.Enum.TryParse(typeof(" + enumType + "), "
                    + local + "Text, ignoreCase: true, out var " + local + "Value))");
                Line(builder, NestedIndent + Indent + Indent + "{");
                Line(builder, NestedIndent + Indent + Indent + Indent + failure);
                Line(builder, NestedIndent + Indent + Indent + "}");
                Line(builder, NestedIndent + Indent + Indent + local + " = (" + parameter.TypeFullName + ")" + local + "Value!;");
                Line(builder, NestedIndent + Indent + "}");
            }

            return;
        }

        var parse = parameter.ScalarKind switch
        {
            AppServiceHttpScalarKind.Guid => "global::System.Guid",
            AppServiceHttpScalarKind.Int16 => "global::System.Int16",
            AppServiceHttpScalarKind.UInt16 => "global::System.UInt16",
            AppServiceHttpScalarKind.Int32 => "global::System.Int32",
            AppServiceHttpScalarKind.Int64 => "global::System.Int64",
            AppServiceHttpScalarKind.UInt32 => "global::System.UInt32",
            AppServiceHttpScalarKind.UInt64 => "global::System.UInt64",
            AppServiceHttpScalarKind.Byte => "global::System.Byte",
            AppServiceHttpScalarKind.SByte => "global::System.SByte",
            AppServiceHttpScalarKind.Boolean => "global::System.Boolean",
            AppServiceHttpScalarKind.Decimal => "global::System.Decimal",
            AppServiceHttpScalarKind.Double => "global::System.Double",
            AppServiceHttpScalarKind.Single => "global::System.Single",
            AppServiceHttpScalarKind.Char => "global::System.Char",
            AppServiceHttpScalarKind.DateTime => "global::System.DateTime",
            AppServiceHttpScalarKind.DateTimeOffset => "global::System.DateTimeOffset",
            _ => throw new InvalidOperationException(AppServiceHttpDiagnosticCodes.UnsupportedDeclaration
                + ": scalar kind '" + parameter.ScalarKind + "' has no bounded binder."),
        };
        Line(builder, NestedIndent + Indent + "var " + local + "Text = " + expression + ";");
        if (parameter.Required)
        {
            Line(builder, NestedIndent + Indent + "if (global::System.String.IsNullOrEmpty(" + local + "Text) || !" + parse
                + ".TryParse(" + local + "Text, out var " + local + "))");
            Line(builder, NestedIndent + Indent + "{");
            Line(builder, NestedIndent + Indent + Indent + failure);
            Line(builder, NestedIndent + Indent + "}");
        }
        else
        {
            Line(builder, NestedIndent + Indent + parameter.TypeFullName + " " + local + " = default!;");
            Line(builder, NestedIndent + Indent + "if (!global::System.String.IsNullOrEmpty(" + local + "Text) && " + parse
                + ".TryParse(" + local + "Text, out var " + local + "Value))");
            Line(builder, NestedIndent + Indent + "{");
            Line(builder, NestedIndent + Indent + Indent + local + " = " + local + "Value;");
            Line(builder, NestedIndent + Indent + "}");
            Line(builder, NestedIndent + Indent + "else if (!global::System.String.IsNullOrEmpty(" + local + "Text))");
            Line(builder, NestedIndent + Indent + "{");
            Line(builder, NestedIndent + Indent + Indent + failure);
            Line(builder, NestedIndent + Indent + "}");
        }
    }

    private static void EmitResultMapper(StringBuilder builder, HttpWireAction action)
    {
        var payload = action.ResultPayloadFullName;
        var require = DynamicApi + "CapabilityEndpointJsonTypeInfoResolver.Require";
        var mapper = DynamicApi + "CompatibilityHttpResultMapper";
        string expression;
        if (payload is null || action.ResultKind is AppServiceHttpResultKind.Void
            or AppServiceHttpResultKind.TaskVoid or AppServiceHttpResultKind.ValueTaskVoid)
        {
            expression = mapper + ".WrapVoidResult(" + require + "<" + VoidEnvelope + ">(serviceProvider))";
        }
        else if (action.MapNotFoundOntoNull)
        {
            expression = mapper + ".WrapGetResult<" + payload + ">(ctx.Output as " + payload + ", "
                + require + "<" + DynamicApi + "DynamicApiResponse<" + payload + ">>(serviceProvider), "
                + require + "<" + VoidEnvelope + ">(serviceProvider))";
        }
        else
        {
            expression = mapper + ".WrapResult<" + payload + ">((" + payload + ")ctx.Output!, "
                + require + "<" + DynamicApi + "DynamicApiResponse<" + payload + ">>(serviceProvider))";
        }

        Line(builder, NestedIndent + "private static object " + MapperName(action) + "(");
        Line(builder, NestedIndent + Indent + DynamicApi + "EndpointExecutionContext ctx,");
        Line(builder, NestedIndent + Indent + "global::System.IServiceProvider serviceProvider)");
        Line(builder, NestedIndent + Indent + "=> " + expression + ";");
        Line(builder, string.Empty);
    }

    private static void EmitInvoker(StringBuilder builder, HttpWireModel model, HttpWireAction action)
    {
        Line(builder, Indent + "internal sealed class " + InvokerName(model.ContributionTypeName, action)
            + " : " + CapabilityAbstractions + "ICapabilityContextAwareHandlerInvoker");
        Line(builder, Indent + "{");
        Line(builder, NestedIndent + "public async global::System.Threading.Tasks.Task<object?> InvokeAsync(");
        Line(builder, NestedIndent + Indent + CapabilityAbstractions + "CapabilityExecutionContext context,");
        Line(builder, NestedIndent + Indent + "global::System.Threading.CancellationToken ct)");
        Line(builder, NestedIndent + "{");
        Line(builder, NestedIndent + Indent + "var service = global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService<"
            + model.ContractFullName + ">(context.ServiceProvider);");
        if (action.UsesEnvelope && action.EnvelopeFullName is not null)
        {
            Line(builder, NestedIndent + Indent + "var envelope = (global::" + action.EnvelopeFullName + ")context.Input!;");
        }
        else
        {
            var single = action.Parameters.FirstOrDefault(parameter => parameter.Source != "CancellationToken");
            if (single is not null)
            {
                Line(builder, NestedIndent + Indent + "var singleInput = (" + single.TypeFullName + ")context.Input!;");
            }
        }

        var arguments = new List<string>();
        foreach (var argument in action.InvokerArguments)
        {
            arguments.Add(argument.Kind switch
            {
                HttpWireArgumentKind.EnvelopeMember => "envelope." + argument.Value,
                HttpWireArgumentKind.CancellationToken => "ct",
                _ => argument.Value,
            });
        }

        var invocation = "service." + action.ContractMethodName + "(" + string.Join(", ", arguments) + ")";
        if (action.MapNotFoundOntoNull)
        {
            Line(builder, NestedIndent + Indent + "try");
            Line(builder, NestedIndent + Indent + "{");
            Line(builder, NestedIndent + Indent + Indent + ResultInvocation(action, invocation));
            Line(builder, NestedIndent + Indent + "}");
            Line(builder, NestedIndent + Indent + "catch (global::CrestCreates.Domain.Shared.Exceptions.CrestEntityNotFoundException)");
            Line(builder, NestedIndent + Indent + "{");
            Line(builder, NestedIndent + Indent + Indent + "return null;");
            Line(builder, NestedIndent + Indent + "}");
        }
        else
        {
            Line(builder, NestedIndent + Indent + ResultInvocation(action, invocation));
        }

        Line(builder, NestedIndent + "}");
        Line(builder, string.Empty);
        Line(builder, NestedIndent + "public global::System.Threading.Tasks.Task<object?> InvokeAsync(object? input, global::System.Threading.CancellationToken ct)");
        Line(builder, NestedIndent + Indent + "=> throw new global::System.InvalidOperationException(");
        Line(builder, NestedIndent + Indent + Indent + "\"The generated projection invoker requires a CapabilityExecutionContext.\");");
        Line(builder, Indent + "}");
        Line(builder, string.Empty);
    }

    private static string ResultInvocation(HttpWireAction action, string invocation) => action.ResultKind switch
    {
        AppServiceHttpResultKind.TaskValue or AppServiceHttpResultKind.ValueTaskValue
            => "return await " + invocation + ".ConfigureAwait(false);",
        AppServiceHttpResultKind.SyncValue => "return " + invocation + ";",
        AppServiceHttpResultKind.TaskVoid or AppServiceHttpResultKind.ValueTaskVoid
            => "await " + invocation + ".ConfigureAwait(false);\n" + Spaces(6) + "return null;",
        _ => invocation + ";\n" + Spaces(6) + "return null;",
    };

    private static string Spaces(int levels) => new string(' ', levels * 4);

    private static IEnumerable<HttpWireJsonRoot> JsonRoots(HttpWireModel model)
    {
        var seen = new HashSet<string>(StringComparer.Ordinal);
        foreach (var action in model.Actions)
        {
            if (action.UsesEnvelope && action.EnvelopeFullName is not null)
            {
                if (seen.Add("Input|" + action.EnvelopeFullName))
                {
                    yield return new HttpWireJsonRoot("global::" + action.EnvelopeFullName, action.Name, "CapabilityInput");
                }

                if (model.EmitInputScalarRoots)
                {
                    foreach (var parameter in action.Parameters.Where(parameter => parameter.Source != "CancellationToken"))
                    {
                        if (seen.Add("Scalar|" + parameter.TypeFullName))
                        {
                            yield return new HttpWireJsonRoot(
                                parameter.TypeFullName, action.Name,
                                parameter.Source == "Body" ? "Body" : "CapabilityInput",
                                parameter.ClrTypeFullName);
                        }
                    }
                }
            }
            else
            {
                var single = action.Parameters.FirstOrDefault(parameter => parameter.Source != "CancellationToken");
                if (single is not null
                    && (model.EmitInputScalarRoots || single.Source == "Body")
                    && seen.Add("Input|" + single.TypeFullName))
                {
                    yield return new HttpWireJsonRoot(
                        single.TypeFullName, action.Name,
                        single.Source == "Body" ? "Body" : "CapabilityInput",
                        single.ClrTypeFullName);
                }
            }

            if (action.ResultPayloadFullName is not null)
            {
                if (seen.Add("Payload|" + action.ResultPayloadFullName))
                {
                    yield return new HttpWireJsonRoot(action.ResultPayloadFullName, action.Name, "Payload");
                }

                var envelope = DynamicApi + "DynamicApiResponse<" + action.ResultPayloadFullName + ">";
                if (seen.Add("Result|" + envelope))
                {
                    yield return new HttpWireJsonRoot(envelope, action.Name, "ResultEnvelope");
                }
            }

            if (action.ResultPayloadFullName is null || action.MapNotFoundOntoNull)
            {
                if (seen.Add("Void|" + action.Name))
                {
                    yield return new HttpWireJsonRoot(VoidEnvelope, action.Name, "VoidEnvelope");
                }
            }
        }

        foreach (var root in model.ExtraJsonRoots)
        {
            if (seen.Add("Extra|" + root.TypeDisplay + "|" + root.Component))
            {
                yield return root;
            }
        }
    }

    private static string EnumTypeForParse(string typeFullName)
    {
        var trimmed = typeFullName.TrimEnd('?');
        if (trimmed.StartsWith("global::System.Nullable<", StringComparison.Ordinal) && trimmed.EndsWith(">", StringComparison.Ordinal))
        {
            return trimmed.Substring("global::System.Nullable<".Length, trimmed.Length - "global::System.Nullable<".Length - 1);
        }

        return trimmed;
    }

    private static string BinderName(HttpWireAction action) => "Bind_" + action.Name + "_Async";

    private static string MapperName(HttpWireAction action) => "MapResult_" + action.Name;

    private static string EnumMethod(string httpMethod) => httpMethod switch
    {
        "GET" => "Get",
        "POST" => "Post",
        "PUT" => "Put",
        "PATCH" => "Patch",
        "DELETE" => "Delete",
        _ => throw new InvalidOperationException(AppServiceHttpDiagnosticCodes.UnsupportedDeclaration
            + ": unsupported HTTP method '" + httpMethod + "'."),
    };

    private static string MessageType(string typeFullName)
        => typeFullName.StartsWith("global::", StringComparison.Ordinal)
            ? typeFullName.Substring("global::".Length)
            : typeFullName;

    private static string StringArray(IReadOnlyList<string> values)
        => values.Count == 0
            ? "global::System.Array.Empty<string>()"
            : "new[] { " + string.Join(", ", values.Select(value => "\"" + Escape(value) + "\"")) + " }";

    private static string Escape(string value) => value.Replace("\\", "\\\\").Replace("\"", "\\\"");

    private static void Line(StringBuilder builder, string text) => builder.AppendLine(text);

    private static string Indent => "    ";
    private static string NestedIndent => "        ";
    private static string QuadIndent => "            ";
    private static string QuintIndent => "                ";
    private static string SextIndent => "                    ";
