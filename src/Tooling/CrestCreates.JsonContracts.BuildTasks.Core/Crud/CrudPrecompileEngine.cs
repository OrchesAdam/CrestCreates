using System;
using System.Collections.Generic;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using CrestCreates.JsonContracts.BuildTasks.Semantic;
using CrestCreates.Tooling.CrudGeneration;
using Microsoft.CodeAnalysis;

namespace CrestCreates.JsonContracts.BuildTasks.Crud;

/// <summary>
/// #128 S2: the isolated-process CRUD precompile producer. It reads authored sources plus the current
/// TFM reference assemblies, builds the frozen <see cref="CrudGenerationModel"/> from real Roslyn
/// symbols (never from CLR assembly loading or reflection), and returns the materialized bundle plus
/// the outputs manifest entries the build stage writes. Errors are returned as diagnostics so the
/// caller fails the build instead of consuming an incomplete surface.
/// </summary>
public sealed class CrudPrecompileEngine
{
    /// <summary>Version of the produced artifacts and manifests; part of the incremental contract.</summary>
    public const string CrudArtifactSchemaVersion = "crud-artifacts-v1";

    public CrudPrecompileResult Run(
        string assemblyName,
        IEnumerable<(string Path, string Text)> sourceFiles,
        IReadOnlyList<string> referencePaths,
        string languageVersion,
        IEnumerable<string> defineConstants,
        string nullable,
        bool allowUnsafeBlocks,
        bool validateOnly = false)
    {
        var sources = sourceFiles.ToList();
        var diagnostics = new List<CrudToolDiagnostic>();

        // Fail closed on an empty reference set: the TRUSTED_PLATFORM_ASSEMBLIES fallback of the JSON
        // compilation factory would otherwise invent a closure the real build never had.
        if (referencePaths is null || referencePaths.Count == 0)
        {
            diagnostics.Add(new CrudToolDiagnostic(
                CrudDiagnosticIds.PrecompileStateInvalid,
                "CRUD precompile received no reference assemblies. The current TFM's "
                + "ReferencePathWithRefAssemblies must be supplied.",
                null, 0, 0));
            return CrudPrecompileResult.Failed(diagnostics);
        }

        var compilation = JsonContractCompilationFactory.CreateCompilation(
            assemblyName + ".CrudPrecompile",
            sources,
            referencePaths,
            languageVersion,
            defineConstants,
            nullable,
            allowUnsafeBlocks);

        var build = CrudGenerationModelBuilder.Build(compilation, assemblyName);
        foreach (var issue in build.Diagnostics)
        {
            diagnostics.Add(new CrudToolDiagnostic(
                issue.Id,
                issue.Message,
                issue.Location?.Path,
                issue.Location?.Line ?? 0,
                issue.Location?.Column ?? 0));
        }

        if (validateOnly)
        {
            // CrestCreatesCodeGeneration=false combined with a live formal declaration is a
            // deterministic build error: the only legal output is no surface at all, and the legacy
            // producer must not quietly take ownership back.
            foreach (var model in build.Models)
            {
                diagnostics.Add(new CrudToolDiagnostic(
                    CrudDiagnosticIds.ToolchainNotAssembled,
                    $"CRUD generation is disabled, but '{model.ServiceFullName}' declares "
                    + "[GenerateCrudService]; the formal CRUD surface cannot be produced by the legacy path.",
                    model.DeclarationLocation.Path,
                    model.DeclarationLocation.Line,
                    model.DeclarationLocation.Column));
            }

            return CrudPrecompileResult.Failed(diagnostics);
        }

        if (diagnostics.Any(diagnostic => IsError(diagnostic.Id)))
        {
            return CrudPrecompileResult.Failed(diagnostics);
        }

        var outputs = new List<CrudOutputManifestEntry>();
        var bundleBuilder = new StringBuilder();
        bundleBuilder.AppendLine("// <auto-generated />");
        bundleBuilder.AppendLine(
            "// CrestCreates CRUD precompile bundle. Owner assembly: " + assemblyName
            + ". Model: " + CrudGenerationModel.ModelSchemaVersion
            + ". Artifacts schema: " + CrudArtifactSchemaVersion + ". Do not edit.");

        // One artifact list: the per-service artifacts plus the single assembly-level activation, so the
        // bundle text and the outputs manifest cover exactly the same set the JSON stage reconciles.
        var models = build.Models.OrderBy(m => m.ServiceFullName, StringComparer.Ordinal).ToArray();
        var modelByOwner = models.ToDictionary(m => m.ServiceFullName, m => m, StringComparer.Ordinal);
        foreach (var item in CrudArtifactEmitter.EmitBundleArtifacts(models))
        {
            bundleBuilder.AppendLine("// ---- artifact: " + item.Artifact.HintName + " ----");
            bundleBuilder.AppendLine(item.Artifact.Source);
            var location = modelByOwner.TryGetValue(item.OwnerServiceFullName, out var owner)
                ? owner.DeclarationLocation.ToString()
                : models[0].DeclarationLocation.ToString();
            outputs.Add(new CrudOutputManifestEntry(
                OwnerAssemblyName: assemblyName,
                OwnerServiceFullName: item.OwnerServiceFullName,
                ArtifactHintName: item.Artifact.HintName,
                DeclaredTypeFullNames: CrudArtifactEmitter.DeclaredTypeFullNames(item.Artifact.Source),
                SourceLocation: location,
                ModelSchemaVersion: CrudGenerationModel.ModelSchemaVersion,
                ContentHash: Sha256(item.Artifact.Source)));
        }

        return new CrudPrecompileResult(
            bundleBuilder.ToString(),
            outputs,
            diagnostics,
            build.Models.Count,
            build.Models);
    }

    // Declared type names come from CrudArtifactEmitter.DeclaredTypeFullNames, the one rule shared with
    // the analyzer and the ownership tests, so the manifest can never record a name the producer did not
    // actually declare.
    private static bool IsError(string id) => id != CrudDiagnosticIds.Info;

    private static string Sha256(string content) =>
        "sha256:" + Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(content))).ToLowerInvariant();
}

public sealed record CrudToolDiagnostic(
    string Id,
    string Message,
    string? FilePath,
    int Line,
    int Column)
{
    public string Severity => "Error";
}

public sealed record CrudOutputManifestEntry(
    string OwnerAssemblyName,
    string OwnerServiceFullName,
    string ArtifactHintName,
    IReadOnlyList<string> DeclaredTypeFullNames,
    string SourceLocation,
    string ModelSchemaVersion,
    string ContentHash);

public sealed record CrudPrecompileResult(
    string BundleSource,
    IReadOnlyList<CrudOutputManifestEntry> Outputs,
    IReadOnlyList<CrudToolDiagnostic> Diagnostics,
    int DeclarationCount,
    IReadOnlyList<CrudGenerationModel> Models)
{
    public bool HasErrors => Diagnostics.Any(diagnostic => diagnostic.Id != CrudDiagnosticIds.Info);

    public static CrudPrecompileResult Failed(IReadOnlyList<CrudToolDiagnostic> diagnostics) =>
        new(string.Empty, Array.Empty<CrudOutputManifestEntry>(), diagnostics, 0, Array.Empty<CrudGenerationModel>());
}
