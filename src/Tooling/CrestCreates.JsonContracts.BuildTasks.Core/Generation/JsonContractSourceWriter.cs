using CrestCreates.JsonContracts.BuildTasks.Model;
using Microsoft.CodeAnalysis;

namespace CrestCreates.JsonContracts.BuildTasks.Generation;

public static class JsonContractSourceWriter
{
    public static string WriteContextSource(JsonContractGenerationModel model, string assemblyName)
    {
        var sb = new System.Text.StringBuilder();

        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("#nullable enable");

        if (model.Contexts.Count == 0 && model.LocalEventRoots.Count == 0
            && model.IntegrationEventRoots.Count == 0 && model.CrudRoots.Count == 0
            && model.AppServiceHttpRoots.Count == 0)
            return sb.ToString();

        var groupedByNamespace = model.Contexts
            .GroupBy(c => c.ContainingNamespace)
            .OrderBy(g => g.Key, StringComparer.Ordinal);

        foreach (var nsGroup in groupedByNamespace)
        {
            var ns = StripGlobalPrefix(nsGroup.Key);
            var isGlobalNs = string.IsNullOrEmpty(ns) || ns == "<global namespace>";

            sb.AppendLine();

            if (!isGlobalNs)
            {
                sb.AppendLine($"namespace {ns}");
                sb.AppendLine("{");
            }

            var first = true;
            foreach (var context in nsGroup.OrderBy(c => c.FullMetadataName, StringComparer.Ordinal))
            {
                if (!first)
                    sb.AppendLine();

                WriteContext(sb, context);
                first = false;
            }

            if (!isGlobalNs)
                sb.AppendLine("}");
        }

        if (model.LocalEventRoots.Count > 0)
        {
            sb.AppendLine();
            WriteLocalEventCodecBlock(sb, model.LocalEventRoots, assemblyName);
        }

        if (model.IntegrationEventRoots.Count > 0)
        {
            sb.AppendLine();
            WriteIntegrationEventCodecBlock(sb, model.IntegrationEventRoots, assemblyName);
        }

        if (model.CrudRoots.Count > 0)
        {
            sb.AppendLine();
            WriteCrudRootBlock(sb, model.CrudRoots, assemblyName);
        }

        if (model.AppServiceHttpRoots.Count > 0)
        {
            sb.AppendLine();
            WriteAppServiceHttpRootBlock(sb, model.AppServiceHttpRoots, assemblyName);
        }

        return sb.ToString();
    }

    /// <summary>
    /// #129 S2.2-B: the hand-written projection roots become one internal context named exactly as the
    /// generated activation references it, so the official STJ generator closes composed envelopes,
    /// body/scalar inputs, payloads and typed result envelopes inside the same CoreCompile. HTTP uses
    /// the camelCase policy of §4.3.
    /// </summary>
    private static void WriteAppServiceHttpRootBlock(
        System.Text.StringBuilder sb,
        List<JsonContractRootModel> roots,
        string assemblyName)
    {
        var contextName = global::CrestCreates.Tooling.HttpProjection.GeneratedHttpJsonContext.TypePrefix
            + global::CrestCreates.Tooling.HttpProjection.AppServiceHttpWireConvention.CanonicalToken(assemblyName);
        sb.AppendLine($"namespace {(global::CrestCreates.Tooling.HttpProjection.GeneratedHttpJsonContext.Namespace)}");
        sb.AppendLine("{");

        foreach (var root in roots.OrderBy(r => r.FullMetadataName, StringComparer.Ordinal))
        {
            var origin = root.Provenance.Origins.FirstOrDefault();
            sb.AppendLine($"    // HTTP projection root from {(origin?.DeclaringSurface ?? assemblyName)}"
                + (origin is null ? string.Empty : " (" + origin.RoleName + ")"));
            sb.AppendLine($"    [global::System.Text.Json.Serialization.JsonSerializable({JsonContractTypeNameWriter.WriteTypeofExpression(root.RootType)})]");
        }

        sb.AppendLine("    [global::System.Text.Json.Serialization.JsonSourceGenerationOptions(PropertyNamingPolicy = global::System.Text.Json.Serialization.JsonKnownNamingPolicy.CamelCase)]");
        sb.AppendLine($"    internal sealed partial class {contextName} : global::System.Text.Json.Serialization.JsonSerializerContext");
        sb.AppendLine("    {");
        sb.AppendLine("    }");
        sb.AppendLine("}");
    }

    private static void WriteLocalEventCodecBlock(
        System.Text.StringBuilder sb,
        List<JsonContractRootModel> roots,
        string assemblyName)
    {
        sb.AppendLine($"namespace {JsonContractBuildConstants.LocalEventGeneratedNamespace}");
        sb.AppendLine("{");

        foreach (var root in roots.OrderBy(r => r.FullMetadataName, StringComparer.Ordinal))
        {
            sb.AppendLine($"    // Replayable local event: {root.FullMetadataName}");
            sb.AppendLine($"    [global::System.Text.Json.Serialization.JsonSerializable({JsonContractTypeNameWriter.WriteTypeofExpression(root.RootType)})]");
        }

        sb.AppendLine($"    internal sealed partial class {JsonContractBuildConstants.LocalEventJsonContextSimpleName} : global::System.Text.Json.Serialization.JsonSerializerContext");
        sb.AppendLine("    {");
        sb.AppendLine("    }");
        sb.AppendLine();

        var escapedOrigin = assemblyName.Replace("\\", "\\\\").Replace("\"", "\\\"");
        sb.AppendLine($"    /// <summary>Registers the source-generated local event codecs as per-host service contributions; called by the assembly's generated AddLocalEvents() extension.</summary>");
        sb.AppendLine($"    internal static class {JsonContractBuildConstants.LocalEventCodecContributionsSimpleName}");
        sb.AppendLine("    {");
        sb.AppendLine("        public static global::Microsoft.Extensions.DependencyInjection.IServiceCollection AddCodecs(");
        sb.AppendLine("            this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)");
        sb.AppendLine("        {");

        foreach (var root in roots.OrderBy(r => r.FullMetadataName, StringComparer.Ordinal))
        {
            var typeOf = JsonContractTypeNameWriter.WriteTypeofExpression(root.RootType);
            sb.AppendLine("            global::Microsoft.Extensions.DependencyInjection.ServiceCollectionServiceExtensions.AddSingleton(");
            sb.AppendLine("                services,");
            sb.AppendLine($"                new {JsonContractBuildConstants.LocalEventCodecRegistrationFullName}");
            sb.AppendLine("                {");
            sb.AppendLine($"                    PayloadType = {typeOf},");
            sb.AppendLine($"                    CodecFactory = static () => {JsonContractBuildConstants.LocalEventJsonContextSimpleName}.Default.GetTypeInfo({typeOf}),");
            sb.AppendLine($"                    Origin = \"{escapedOrigin}\",");
            sb.AppendLine("                });");
        }

        sb.AppendLine("            return services;");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");
    }

    /// <summary>
    /// #128 S2: the CRUD roots become one internal context in the generated file, so the official STJ
    /// generator closes the DTOs, the paged payload, the typed and void envelopes and the composed
    /// capability inputs in the same CoreCompile. HTTP uses the camelCase policy of §7.1.
    /// </summary>
    private static void WriteCrudRootBlock(
        System.Text.StringBuilder sb,
        List<JsonContractRootModel> roots,
        string assemblyName)
    {
        // The CRUD context namespace is owned by the shared CRUD generation convention, which the
        // generated activation also references (one definition for both sides).
        var crudNamespace = global::CrestCreates.Tooling.CrudGeneration.CrudJsonContractConvention.GeneratedNamespace;
        sb.AppendLine($"namespace {crudNamespace}");
        sb.AppendLine("{");

        foreach (var root in roots.OrderBy(r => r.FullMetadataName, StringComparer.Ordinal))
        {
            var origin = root.Provenance.Origins.FirstOrDefault();
            sb.AppendLine($"    // CRUD root from {(origin?.DeclaringSurface ?? assemblyName)}");
            sb.AppendLine($"    [global::System.Text.Json.Serialization.JsonSerializable({JsonContractTypeNameWriter.WriteTypeofExpression(root.RootType)})]");
        }

        sb.AppendLine("    [global::System.Text.Json.Serialization.JsonSourceGenerationOptions(PropertyNamingPolicy = global::System.Text.Json.Serialization.JsonKnownNamingPolicy.CamelCase)]");
        sb.AppendLine($"    internal sealed partial class {JsonContractBuildConstants.CrudJsonContextSimpleName} : global::System.Text.Json.Serialization.JsonSerializerContext");
        sb.AppendLine("    {");
        sb.AppendLine("    }");
        sb.AppendLine("}");
    }

    private static void WriteIntegrationEventCodecBlock(
        System.Text.StringBuilder sb,
        List<JsonContractRootModel> roots,
        string assemblyName)
    {
        sb.AppendLine($"namespace {JsonContractBuildConstants.LocalEventGeneratedNamespace}");
        sb.AppendLine("{");

        foreach (var root in roots.OrderBy(r => r.FullMetadataName, StringComparer.Ordinal))
        {
            sb.AppendLine($"    // Integration event: {root.FullMetadataName}");
            sb.AppendLine($"    [global::System.Text.Json.Serialization.JsonSerializable({JsonContractTypeNameWriter.WriteTypeofExpression(root.RootType)})]");
        }

        // Wire payloads use one explicit, stable naming policy (camelCase, matching the envelope):
        // the generated codec is the single serializer for publish/consume/redelivery.
        sb.AppendLine("    [global::System.Text.Json.Serialization.JsonSourceGenerationOptions(PropertyNamingPolicy = global::System.Text.Json.Serialization.JsonKnownNamingPolicy.CamelCase)]");
        sb.AppendLine($"    internal sealed partial class {JsonContractBuildConstants.EventJsonContextSimpleName} : global::System.Text.Json.Serialization.JsonSerializerContext");
        sb.AppendLine("    {");
        sb.AppendLine("    }");
        sb.AppendLine();

        var escapedOrigin = assemblyName.Replace("\\", "\\\\").Replace("\"", "\\\"");
        sb.AppendLine($"    /// <summary>Registers the source-generated integration event codecs as per-host service contributions; called by the assembly's generated AddEventDescriptors() extension.</summary>");
        sb.AppendLine($"    internal static class {JsonContractBuildConstants.EventJsonCodecContributionsSimpleName}");
        sb.AppendLine("    {");
        sb.AppendLine("        public static global::Microsoft.Extensions.DependencyInjection.IServiceCollection AddCodecs(");
        sb.AppendLine("            this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)");
        sb.AppendLine("        {");

        foreach (var root in roots.OrderBy(r => r.FullMetadataName, StringComparer.Ordinal))
        {
            var typeOf = JsonContractTypeNameWriter.WriteTypeofExpression(root.RootType);
            sb.AppendLine("            global::Microsoft.Extensions.DependencyInjection.ServiceCollectionServiceExtensions.AddSingleton(");
            sb.AppendLine("                services,");
            sb.AppendLine($"                new {JsonContractBuildConstants.EventJsonCodecRegistrationFullName}");
            sb.AppendLine("                {");
            sb.AppendLine($"                    PayloadType = {typeOf},");
            sb.AppendLine($"                    CodecFactory = static () => {JsonContractBuildConstants.EventJsonContextSimpleName}.Default.GetTypeInfo({typeOf}),");
            sb.AppendLine($"                    Origin = \"{escapedOrigin}\",");
            sb.AppendLine("                });");
        }

        sb.AppendLine("            return services;");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");
    }

    private static void WriteContext(System.Text.StringBuilder sb, JsonContractContextModel context)
    {
        var rootsToGenerate = context.AllDirectRoots
            .OrderBy(r => r.FullMetadataName, StringComparer.Ordinal)
            .ToList();

        foreach (var root in rootsToGenerate)
        {
            var provenanceComment = BuildProvenanceComment(root);
            if (provenanceComment.Length > 0)
                sb.AppendLine($"    {provenanceComment}");

            sb.AppendLine($"    [global::System.Text.Json.Serialization.JsonSerializable(typeof({root.FullMetadataName}))]");
        }

        var contextAccess = context.DeclaredAccessibility == "Public" ? "public" : "internal";
        sb.AppendLine($"    {contextAccess} partial class {context.ContextSimpleName}");

        var manifestAccess = context.ManifestAccessibility == JsonContractManifestAccessibility.Public
            ? "public"
            : "internal";

        sb.AppendLine($"    {{");
        sb.AppendLine($"        {manifestAccess} static class {context.ManifestClassName}");
        sb.AppendLine($"        {{");

        WriteManifestSet(sb, "SurfaceRootTypes", context.SurfaceRoots, manifestAccess);
        WriteManifestSet(sb, "BindingRootTypes", context.BindingRoots, manifestAccess);
        WriteManifestSet(sb, "ExplicitRootTypes", context.ExplicitRoots, manifestAccess);
        WriteManifestSet(sb, "AllDirectRootTypes", context.AllDirectRoots, manifestAccess);

        sb.AppendLine($"        }}");
        sb.AppendLine($"    }}");
    }

    private static void WriteManifestSet(System.Text.StringBuilder sb, string propertyName, List<JsonContractRootModel> roots, string accessibility)
    {
        var sortedRoots = roots.OrderBy(r => r.FullMetadataName, StringComparer.Ordinal).ToList();

        if (sortedRoots.Count == 0)
        {
            sb.AppendLine($"            private static readonly global::System.Collections.Frozen.FrozenSet<global::System.Type> {propertyName}Backing =");
            sb.AppendLine($"                global::System.Collections.Frozen.FrozenSet<global::System.Type>.Empty;");
        }
        else
        {
            sb.AppendLine($"            private static readonly global::System.Collections.Frozen.FrozenSet<global::System.Type> {propertyName}Backing =");
            sb.Append($"                global::System.Collections.Frozen.FrozenSet.Create<global::System.Type>(new global::System.Type[] {{ ");
            sb.Append(string.Join(", ", sortedRoots.Select(r => JsonContractTypeNameWriter.WriteTypeofExpression(r.RootType))));
            sb.AppendLine(" });");
        }

        sb.AppendLine($"            {accessibility} static global::System.Collections.Generic.IReadOnlySet<global::System.Type> {propertyName} => {propertyName}Backing;");
        sb.AppendLine();
    }

    private static string BuildProvenanceComment(JsonContractRootModel root)
    {
        var origins = root.Provenance.Origins
            .OrderBy(origin => origin.Identity, StringComparer.Ordinal)
            .ToList();

        if (origins.Count == 0 || origins.All(origin => origin.SourceKind == JsonContractRootSourceKind.Explicit))
            return $"// Explicit extra: {root.FullMetadataName}";

        var sourceLabel = origins.Any(origin => origin.SourceKind is JsonContractRootSourceKind.AgentToolInput
            or JsonContractRootSourceKind.AgentToolOutput
            or JsonContractRootSourceKind.McpToolInput
            or JsonContractRootSourceKind.McpToolOutput)
            ? "Binding root"
            : "Surface root";

        return $"// {sourceLabel}: {root.FullMetadataName} from {string.Join(", ", origins.Select(origin => origin.ToDisplayString()))}";
    }

    private static string StripGlobalPrefix(string ns)
    {
        if (ns.StartsWith("global::", StringComparison.Ordinal))
            return ns.Substring("global::".Length);
        return ns;
    }
}
