using CrestCreates.JsonContracts.BuildTasks.Model;
using Microsoft.CodeAnalysis;

namespace CrestCreates.JsonContracts.BuildTasks.Generation;

public static class JsonContractSourceWriter
{
    public static string WriteContextSource(JsonContractGenerationModel model)
    {
        var sb = new System.Text.StringBuilder();

        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("#nullable enable");

        if (model.Contexts.Count == 0)
            return sb.ToString();

        var groupedByNamespace = model.Contexts
            .GroupBy(c => c.ContainingNamespace)
            .OrderBy(g => g.Key, StringComparer.Ordinal);

        foreach (var nsGroup in groupedByNamespace)
        {
            var ns = StripGlobalPrefix(nsGroup.Key);
            var isGlobalNs = string.IsNullOrEmpty(ns) || ns == "<global namespace>";

            sb.AppendLine();

            if (!isGlobalNs)
            {
                sb.AppendLine($"namespace {ns}");
                sb.AppendLine("{");
            }

            var first = true;
            foreach (var context in nsGroup.OrderBy(c => c.FullMetadataName, StringComparer.Ordinal))
            {
                if (!first)
                    sb.AppendLine();

                WriteContext(sb, context);
                first = false;
            }

            if (!isGlobalNs)
                sb.AppendLine("}");
        }

        return sb.ToString();
    }

    private static void WriteContext(System.Text.StringBuilder sb, JsonContractContextModel context)
    {
        var rootsToGenerate = context.AllDirectRoots
            .OrderBy(r => r.FullMetadataName, StringComparer.Ordinal)
            .ToList();

        foreach (var root in rootsToGenerate)
        {
            var provenanceComment = BuildProvenanceComment(root);
            if (provenanceComment.Length > 0)
                sb.AppendLine($"    {provenanceComment}");

            sb.AppendLine($"    [global::System.Text.Json.Serialization.JsonSerializable(typeof({root.FullMetadataName}))]");
        }

        var contextAccess = context.DeclaredAccessibility == "Public" ? "public" : "internal";
        sb.AppendLine($"    {contextAccess} partial class {context.ContextSimpleName}");

        var manifestAccess = context.ManifestAccessibility == JsonContractManifestAccessibility.Public
            ? "public"
            : "internal";

        sb.AppendLine($"    {{");
        sb.AppendLine($"        {manifestAccess} static class {context.ManifestClassName}");
        sb.AppendLine($"        {{");

        WriteManifestSet(sb, "SurfaceRootTypes", context.SurfaceRoots, manifestAccess);
        WriteManifestSet(sb, "BindingRootTypes", context.BindingRoots, manifestAccess);
        WriteManifestSet(sb, "ExplicitRootTypes", context.ExplicitRoots, manifestAccess);
        WriteManifestSet(sb, "AllDirectRootTypes", context.AllDirectRoots, manifestAccess);

        sb.AppendLine($"        }}");
        sb.AppendLine($"    }}");
    }

    private static void WriteManifestSet(System.Text.StringBuilder sb, string propertyName, List<JsonContractRootModel> roots, string accessibility)
    {
        var sortedRoots = roots.OrderBy(r => r.FullMetadataName, StringComparer.Ordinal).ToList();

        if (sortedRoots.Count == 0)
        {
            sb.AppendLine($"            private static readonly global::System.Collections.Frozen.FrozenSet<global::System.Type> {propertyName}Backing =");
            sb.AppendLine($"                global::System.Collections.Frozen.FrozenSet<global::System.Type>.Empty;");
        }
        else
        {
            sb.AppendLine($"            private static readonly global::System.Collections.Frozen.FrozenSet<global::System.Type> {propertyName}Backing =");
            sb.Append($"                global::System.Collections.Frozen.FrozenSet.Create<global::System.Type>(new global::System.Type[] {{ ");
            sb.Append(string.Join(", ", sortedRoots.Select(r => JsonContractTypeNameWriter.WriteTypeofExpression(r.RootType))));
            sb.AppendLine(" });");
        }

        sb.AppendLine($"            {accessibility} static global::System.Collections.Generic.IReadOnlySet<global::System.Type> {propertyName} => {propertyName}Backing;");
        sb.AppendLine();
    }

    private static string BuildProvenanceComment(JsonContractRootModel root)
    {
        var origins = root.Provenance.Origins
            .OrderBy(origin => origin.Identity, StringComparer.Ordinal)
            .ToList();

        if (origins.Count == 0 || origins.All(origin => origin.SourceKind == JsonContractRootSourceKind.Explicit))
            return $"// Explicit extra: {root.FullMetadataName}";

        var sourceLabel = origins.Any(origin => origin.SourceKind is JsonContractRootSourceKind.AgentToolInput
            or JsonContractRootSourceKind.AgentToolOutput
            or JsonContractRootSourceKind.McpToolInput
            or JsonContractRootSourceKind.McpToolOutput)
            ? "Binding root"
            : "Surface root";

        return $"// {sourceLabel}: {root.FullMetadataName} from {string.Join(", ", origins.Select(origin => origin.ToDisplayString()))}";
    }

    private static string StripGlobalPrefix(string ns)
    {
        if (ns.StartsWith("global::", StringComparison.Ordinal))
            return ns.Substring("global::".Length);
        return ns;
    }
}
