using System;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using CrestCreates.CodeGenerator.Models;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace CrestCreates.CodeGenerator.SchemaCapabilityGenerator;

[Generator]
public sealed class HandlerInvokerSourceGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var handlerClasses = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (node, _) => node is ClassDeclarationSyntax cds
                    && cds.BaseList?.Types.Count > 0,
                transform: static (ctx, ct) => GetHandlerInfo(ctx))
            .Where(static x => x is not null)
            .Collect();

        var compilationProvider = context.CompilationProvider;

        context.RegisterSourceOutput(
            handlerClasses.Combine(compilationProvider),
            static (spc, source) =>
            {
                GenerateHandlerRegistrations(spc, source.Left, source.Right);
            });
    }

    private static HandlerInvokerInfo? GetHandlerInfo(GeneratorSyntaxContext ctx)
    {
        var classDecl = (ClassDeclarationSyntax)ctx.Node;
        var symbol = ctx.SemanticModel.GetDeclaredSymbol(classDecl) as INamedTypeSymbol;
        if (symbol == null) return null;

        var handlerType = ctx.SemanticModel.Compilation
            .GetTypeByMetadataName("CrestCreates.Capability.Abstractions.ICapabilityHandler`2");
        if (handlerType == null) return null;

        var genericHandler = symbol.AllInterfaces
            .FirstOrDefault(i => i.IsGenericType
                && i.OriginalDefinition.Equals(handlerType, SymbolEqualityComparer.Default));

        if (genericHandler == null) return null;

        var inputType = genericHandler.TypeArguments[0];
        var outputType = genericHandler.TypeArguments[1];

        var capabilityName = GetCapabilityName(symbol);

        return new HandlerInvokerInfo
        {
            HandlerTypeName = symbol.Name,
            HandlerNamespace = symbol.ContainingNamespace?.ToDisplayString() ?? string.Empty,
            CapabilityName = capabilityName,
            InputTypeName = inputType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
            OutputTypeName = outputType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)
        };
    }

    private static string GetCapabilityName(INamedTypeSymbol symbol)
    {
        var attr = symbol.GetAttributes()
            .FirstOrDefault(a => a.AttributeClass?.Name is "CapabilityNameAttribute" or "CapabilityName");
        if (attr != null && attr.ConstructorArguments.Length > 0)
            return attr.ConstructorArguments[0].Value?.ToString() ?? string.Empty;

        return symbol.Name
            .Replace("Handler", "")
            .Replace("AppService", "")
            .ToLowerInvariant();
    }

    private static void GenerateHandlerRegistrations(
        SourceProductionContext spc,
        ImmutableArray<HandlerInvokerInfo?> handlers,
        Compilation compilation)
    {
        var hasCapability = compilation.ReferencedAssemblyNames
            .Any(a => a.Name == "CrestCreates.Capability.Abstractions");
        if (!hasCapability) return;

        var validHandlers = handlers.Where(h => h != null).ToList();
        if (validHandlers.Count == 0) return;

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("using CrestCreates.Capability.Abstractions;");
        sb.AppendLine("using CrestCreates.Capability;");
        sb.AppendLine("using System.Runtime.CompilerServices;");
        sb.AppendLine();
        sb.AppendLine("namespace CrestCreates.Generated;");
        sb.AppendLine();
        sb.AppendLine("internal static class GeneratedHandlerRegistry");
        sb.AppendLine("{");
        sb.AppendLine("    [ModuleInitializer]");
        sb.AppendLine("    internal static void Register()");
        sb.AppendLine("    {");

        foreach (var handler in validHandlers)
        {
            if (handler == null) continue;
            var fullName = string.IsNullOrEmpty(handler.HandlerNamespace)
                ? handler.HandlerTypeName
                : $"{handler.HandlerNamespace}.{handler.HandlerTypeName}";

            sb.AppendLine($"        // Handler: {fullName}");
            sb.AppendLine($"        // Input: {handler.InputTypeName} → Output: {handler.OutputTypeName}");
            sb.AppendLine($"        // Capability: {handler.CapabilityName}");
            sb.AppendLine("        // Source-generated invoker registration will be emitted here");
            sb.AppendLine("        // when the handler project references CrestCreates.Capability.");
            sb.AppendLine();
        }

        sb.AppendLine("    }");
        sb.AppendLine("}");

        spc.AddSource("GeneratedHandlerRegistry.g.cs", sb.ToString());
    }
}
