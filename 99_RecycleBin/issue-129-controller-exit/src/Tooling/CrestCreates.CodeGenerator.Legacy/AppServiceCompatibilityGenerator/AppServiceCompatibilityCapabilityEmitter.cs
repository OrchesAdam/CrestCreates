using System.Text;

namespace CrestCreates.CodeGenerator.AppServiceCompatibilityGenerator;

/// <summary>
/// Emits an IDescriptorProvider&gt;CapabilityDescriptor&lt; implementation
/// for a single projected CrestService, registered via [ModuleInitializer].
/// </summary>
internal static class AppServiceCompatibilityCapabilityEmitter
{
    public static string Emit(CompatibilityServiceModel service)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using CrestCreates.Capability.Abstractions;");
        sb.AppendLine("using CrestCreates.Metadata;");
        sb.AppendLine("using CrestCreates.Metadata.Abstractions;");
        sb.AppendLine("using CrestCreates.Metadata.Abstractions.DescriptorCapability;");
        sb.AppendLine("using System.Runtime.CompilerServices;");
        sb.AppendLine();
        sb.AppendLine("namespace CrestCreates.Generated;");
        sb.AppendLine();

        sb.AppendLine($"internal sealed class GeneratedAppServiceCompatibilityCapabilities_{service.SanitizedIdentifier} : IDescriptorProvider<CapabilityDescriptor>");
        sb.AppendLine("{");
        sb.AppendLine("    public IReadOnlyList<CapabilityDescriptor> GetDescriptors()");
        sb.AppendLine("    {");
        sb.AppendLine("        return new CapabilityDescriptor[]");
        sb.AppendLine("        {");

        foreach (var action in service.Actions)
        {
            var capabilityKind = action.HttpMethod == "GET" ? "CapabilityKind.Query" : "CapabilityKind.Command";
            var permissionExpr = string.IsNullOrEmpty(action.PermissionName)
                ? "Array.Empty<string>()"
                : $"new[] {{ \"{Escape(action.PermissionName)}\" }}";

            sb.AppendLine("            new CapabilityDescriptor");
            sb.AppendLine("            {");
            sb.AppendLine("                Namespace = \"capability\",");
            sb.AppendLine($"                Id = \"{Escape(action.CapabilityId)}\",");
            sb.AppendLine($"                Name = \"{Escape(action.ActionName)}\",");
            sb.AppendLine("                State = DescriptorState.Active,");
            sb.AppendLine("                Version = 1,");
            sb.AppendLine($"                CapabilityKind = {capabilityKind},");
            sb.AppendLine($"                Permissions = {permissionExpr},");
            sb.AppendLine("                RiskLevel = CapabilityRiskLevel.Medium,");
            sb.AppendLine("                InputSchema = null,");
            sb.AppendLine("                OutputSchema = null,");
            sb.AppendLine("                ProjectionKind = CapabilityProjectionKind.AppServiceCompatibility,");
            sb.AppendLine("            },");
        }

        sb.AppendLine("        };");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();

        // ModuleInitializer for registration
        sb.AppendLine($"internal static class GeneratedAppServiceCompatibilityCapabilitiesBootstrapper_{service.SanitizedIdentifier}");
        sb.AppendLine("{");
        sb.AppendLine("    [ModuleInitializer]");
        sb.AppendLine("    internal static void Register()");
        sb.AppendLine("    {");
        sb.AppendLine($"        DescriptorProviderRegistry.Register<CapabilityDescriptor>(new GeneratedAppServiceCompatibilityCapabilities_{service.SanitizedIdentifier}());");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        return sb.ToString();
    }

    private static string Escape(string value) => value.Replace("\\", "\\\\").Replace("\"", "\\\"");
}
